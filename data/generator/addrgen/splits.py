"""Builds the generated splits (dev, calibration, test) from the project seed.

Each split draws record numbers from its own range, so ids never repeat across splits. A record is also skipped if its
ground-truth address (country plus gold, normalised) was already taken, so no address appears in two splits (or twice
in one). Tiers rotate with the position inside each country, so countries and tiers stay balanced to within one record.
"""
from __future__ import annotations

import hashlib
import json
import unicodedata
from collections import Counter
from dataclasses import dataclass

from addrgen import countries
from addrgen.difficulty import DIFFICULTIES
from addrgen.generate import DEFAULT_TYPO_RATE, generate_record


@dataclass(frozen=True)
class SplitSpec:
    name: str
    size: int
    first_index: int  # first record number tried, within every country


# Index ranges are far apart, so they can never meet however many collisions are skipped.
GENERATED_SPLITS = (
    SplitSpec("dev", 600, 0),
    SplitSpec("calibration", 400, 10_000),
    SplitSpec("test", 1000, 20_000),
)
SPLIT_FILES = {"dev": "dev.jsonl", "calibration": "calibration.jsonl", "test": "test.jsonl", "hard": "hard.jsonl"}


def _norm(value: str) -> str:
    return " ".join(unicodedata.normalize("NFC", value).casefold().split())


def gold_key(record: dict) -> str:
    """The identity of a ground-truth address: its country and gold fields, case-folded and whitespace-collapsed."""
    items = sorted((name, _norm(value)) for name, value in record["gold"].items())
    return json.dumps([record["country"], items], ensure_ascii=False, separators=(",", ":"))


def key_hash(record: dict) -> str:
    return hashlib.sha256(gold_key(record).encode("utf-8")).hexdigest()


def build_split(seed: int, spec: SplitSpec, taken: set[str], codes: list[str] | None = None,
                typo_rate: float = DEFAULT_TYPO_RATE) -> list[dict]:
    """One split. `taken` holds the keys of every address already used; this split's keys are added to it."""
    codes = codes or countries.codes()
    if spec.size % len(codes):
        raise ValueError(f"{spec.name}: size {spec.size} does not divide evenly over {len(codes)} countries")
    per_country = spec.size // len(codes)
    per_slot: dict[str, list[dict]] = {}
    for offset, code in enumerate(codes):
        out, index = [], spec.first_index
        while len(out) < per_country:
            # Offset by the country's position, so the one-record remainders do not all fall on the same tier.
            tier = DIFFICULTIES[(len(out) + offset) % len(DIFFICULTIES)]
            record = generate_record(seed, code, index, tier, typo_rate)
            index += 1
            key = gold_key(record)
            if key in taken:
                continue
            taken.add(key)
            out.append(record)
        per_slot[code] = out
    # Round-robin over the countries, as the generator does.
    return [per_slot[code][i] for i in range(per_country) for code in codes]


def build_all(seed: int, specs=GENERATED_SPLITS, codes: list[str] | None = None) -> dict[str, list[dict]]:
    taken: set[str] = set()
    return {spec.name: build_split(seed, spec, taken, codes) for spec in specs}


def dump_jsonl(records) -> bytes:
    """The exact bytes of a split file: UTF-8, LF line endings, one record per line."""
    return "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in records).encode("utf-8")


def counts(records) -> dict:
    """Counts by country, difficulty and country x difficulty, for the manifest (no address content)."""
    return {
        "records": len(records),
        "by_country": dict(sorted(Counter(r["country"] for r in records).items())),
        "by_difficulty": dict(sorted(Counter(r["difficulty"] for r in records).items())),
        "by_country_difficulty": {
            f"{c}/{d}": n for (c, d), n in sorted(Counter((r["country"], r["difficulty"]) for r in records).items())
        },
    }


def file_sha256(path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def write_splits(out_dir, seed: int) -> dict:
    """Writes dev, calibration and test, splits.manifest.json and test.sha256 into out_dir; returns the manifest.

    The test split is frozen: once test.sha256 exists, this never rewrites test.jsonl. It only confirms that the
    regenerated bytes hash to the frozen value, and refuses to go on if they do not.
    """
    from pathlib import Path

    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    splits = build_all(seed)
    frozen = out / "test.sha256"
    manifest: dict = {"seed": seed, "splits": {}}
    for name, records in splits.items():
        data = dump_jsonl(records)
        digest = hashlib.sha256(data).hexdigest()
        target = out / SPLIT_FILES[name]
        if name == "test" and frozen.exists():
            if frozen.read_text().split()[0] != digest:
                raise SystemExit("refusing to continue: regenerated test split differs from the frozen hash in test.sha256")
        else:
            target.write_bytes(data)
        manifest["splits"][name] = {
            "file": SPLIT_FILES[name], "sha256": digest, **counts(records),
            "key_hashes": sorted(key_hash(r) for r in records),
        }
    if not frozen.exists():
        frozen.write_text(f"{manifest['splits']['test']['sha256']}  {SPLIT_FILES['test']}\n")
    (out / "splits.manifest.json").write_text(json.dumps(manifest, indent=1) + "\n", encoding="utf-8")
    return manifest
